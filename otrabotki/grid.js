  const textLines = (c, n, gap = 5) => { let o = ""; for (let k = 0; k < n; k++) o += `<rect x="${c[0].toFixed(1)}" y="${(c[1] + k * gap).toFixed(1)}" width="${(c[2] * (k === n - 1 ? .6 : 1)).toFixed(1)}" height="2" fill="${INK}" opacity=".55"/>`; return o; };

